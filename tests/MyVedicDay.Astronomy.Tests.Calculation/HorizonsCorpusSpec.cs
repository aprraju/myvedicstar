using System.Text.Json;
using System.Text.Json.Serialization;
using MyVedicStar.Astronomy.Core;
using NodaTime;
using NodaTime.Text;

namespace MyVedicDay.Astronomy.Tests.Calculation;

/// <summary>
/// A case category in the AST-09 corpus (issue #74, AC-1).
/// </summary>
/// <remarks>
/// The category is part of the case identity because AC-1 requires counts reported <i>per category</i>; a single
/// "10000 cases" number would satisfy the total while leaving a dimension - say sunrise/sunset - at zero.
/// </remarks>
public enum CorpusCategory
{
    PlanetaryPositions,
    TithiNakshatraTransitions,
    SunriseSunset,
    Lagna,
    Ayanamsa,
    HistoricalDates
}

/// <summary>One enumerated AST-09 case: what is compared, where, when and under which conventions.</summary>
/// <param name="Id">Stable, deterministic identity so a failure names a case a reader can look up.</param>
/// <param name="Category">The reporting category this case counts toward.</param>
/// <param name="Body">The body under test; null for cases that are not per-body (ayanamsa, sunrise/sunset).</param>
/// <param name="JulianDayUt">Instant, Julian Day UT - the argument <see cref="IEphemeris"/> and graha providers take.</param>
/// <param name="SiteId">Observer site for cases that need one; null for geocentric cases.</param>
/// <param name="Conventions">Frame and node settings the reference was taken under.</param>
public sealed record CorpusCase(
    string Id,
    CorpusCategory Category,
    CelestialBody? Body,
    double JulianDayUt,
    string? SiteId,
    string Conventions)
{
    public override string ToString() => $"{Id} [{Category}{(Body is null ? "" : ", " + Body)}, JD {JulianDayUt:R}]";
}

/// <summary>
/// The AST-09 case matrix, read from <c>astronomy/horizons-corpus-spec.json</c> (issue #74, architect section B).
/// </summary>
/// <remarks>
/// <para><b>Why the matrix is data plus code, not data alone.</b> The architect's requirement is that the corpus be
/// generated by script from a committed spec rather than hand-assembled, and that its composition be reviewed once and
/// then held fixed. Reading the whole matrix from JSON would make the spec the only source, and a spec that lists
/// counts but not their derivation can drift from any enumeration silently. Here the JSON declares the dimensions
/// (bodies, span, sites, ayanamsas, per-category counts, tolerances) and this class owns the arithmetic that reaches
/// them; <see cref="CaseCountsMatchTheSpec"/> fails when the two disagree, so a change to either is a diff and a test
/// result, not a quiet narrowing.</para>
/// <para><b>Determinism.</b> Dates are spread by arithmetic over the declared span rather than randomly, so the same
/// spec yields a byte-identical case list on every run and every machine. That is what makes the corpus reviewable: a
/// reviewer can recompute case 4127 by hand instead of accepting a seed.</para>
/// <para><b>What these cases are not.</b> Enumerating a case is not evidence of accuracy. The case carries a
/// <see cref="CorpusCase.Conventions"/> string and an instant; the corresponding Horizons value lives in the checked-in
/// reference artifact. Until a reference row exists for a case, the case is <i>unmeasured</i> and must be reported as
/// such - never scored as a pass (@see HorizonsCorpusTests).</para>
/// </remarks>
public sealed class HorizonsCorpusSpec
{
    public const string FileName = "horizons-corpus-spec.json";

    private static readonly JsonSerializerOptions SerializerOptions = new()
    {
        PropertyNamingPolicy = JsonNamingPolicy.CamelCase,
        Converters = { new JsonStringEnumConverter() }
    };

    private HorizonsCorpusSpec(CorpusSpecDocument document)
    {
        Document = document;
    }

    public CorpusSpecDocument Document { get; }

    /// <summary>The spec with the declared dimension lists and per-category counts.</summary>
    public IReadOnlyList<CelestialBody> Bodies => Document.Bodies;

    public IReadOnlyList<CorpusSite> Sites => Document.Sites;

    public IReadOnlyList<AyanamsaKind> Ayanamsas => Document.Ayanamsas;

    public IReadOnlyList<CorpusEdgeCase> EdgeCases => Document.EdgeCases;

    public int MinimumTotalCases => Document.MinimumTotalCases;

    public CorpusTolerances Tolerances => Document.Tolerances;

    /// <summary>Loads the spec from a directory or from <c>astronomy/</c> beneath it, as the other fixtures do.</summary>
    /// <remarks>
    /// <paramref name="solutionRoot"/> may name the JSON file itself, which is how the loader is exercised against an
    /// edited copy without mutating the checked-in one. A directory-only signature forced the falsifiability test to
    /// copy the file into a temp directory under the expected name - which silently tested "file not found" instead of
    /// the refusal it was written for.
    /// </remarks>
    public static HorizonsCorpusSpec Load(string solutionRoot)
    {
        var path = ResolvePath(solutionRoot);
        var document = JsonSerializer.Deserialize<CorpusSpecDocument>(File.ReadAllText(path), SerializerOptions)
                       ?? throw new InvalidOperationException($"AST-09 corpus spec '{FileName}' is empty or invalid.");

        Validate(document);
        return new HorizonsCorpusSpec(document);
    }

    private static string ResolvePath(string solutionRoot)
    {
        // Any existing FILE is loaded as-is: the falsifiability test needs to point at an edited copy under a temp
        // name, and enforcing the file name here made that test hit a not-found path instead of the refusal.
        if (File.Exists(solutionRoot))
            return solutionRoot;

        var direct = Path.Combine(solutionRoot, FileName);
        var nested = Path.Combine(solutionRoot, "astronomy", FileName);
        var path = File.Exists(direct) ? direct : nested;
        if (!File.Exists(path))
            throw new FileNotFoundException(
                $"AST-09 corpus spec '{FileName}' is missing at '{direct}' or '{nested}'. The corpus cannot be " +
                "enumerated without it.", path);
        return path;
    }

    /// <summary>
    /// Enumerates every case, deterministically, in a fixed category order.
    /// </summary>
    public IReadOnlyList<CorpusCase> Enumerate()
    {
        var cases = new List<CorpusCase>();
        EnumeratePlanetaryPositions(cases);
        EnumerateTransitions(cases);
        EnumerateSunriseSunset(cases);
        EnumerateLagna(cases);
        EnumerateAyanamsa(cases);
        EnumerateHistoricalDates(cases);
        return cases;
    }

    /// <summary>Case count per category, which is what AC-1 asks to be reported.</summary>
    public IReadOnlyDictionary<CorpusCategory, int> CountByCategory(IEnumerable<CorpusCase> cases)
    {
        var counts = Enum.GetValues<CorpusCategory>().ToDictionary(category => category, _ => 0);
        foreach (var group in cases.GroupBy(caseItem => caseItem.Category))
            counts[group.Key] = group.Count();
        return counts;
    }

    /// <summary>
    /// Planetary positions: every declared body at every declared epoch, with both node conventions carried on the
    /// case rather than doubling the body list.
    /// </summary>
    /// <remarks>
    /// Node conventions are a property of the case, not of the body, because <see cref="CelestialBody.MeanNode"/> and
    /// <see cref="CelestialBody.TrueNode"/> are separate identifiers; carrying the convention here keeps the case
    /// self-describing for the reference lookup without inventing a body that the engine cannot produce.
    /// </remarks>
    private void EnumeratePlanetaryPositions(List<CorpusCase> cases)
    {
        var target = Document.CaseCounts.PlanetaryPositions;
        var epochs = Epochs(target, Document.Bodies.Count);
        for (var index = 0; index < epochs.Count; index++)
        {
            var body = Document.Bodies[index % Document.Bodies.Count];
            cases.Add(new CorpusCase(
                $"planetary-{index:D5}-{body}",
                CorpusCategory.PlanetaryPositions,
                body,
                epochs[index],
                SiteId: null,
                Conventions: $"tropical|mean-equinox-of-date|{NodeConventionFor(body)}"));
        }
    }

    /// <summary>
    /// Tithi/Nakshatra transitions: walk the Moon through the 30 tithi and 27 nakshatra boundaries at a declared site,
    /// spread over the span so the boundary-crossing finder meets both slow and fast lunar motion.
    /// </summary>
    private void EnumerateTransitions(List<CorpusCase> cases)
    {
        var target = Document.CaseCounts.TithiNakshatraTransitions;
        var epochs = Epochs(target, Document.Sites.Count);
        for (var index = 0; index < epochs.Count; index++)
        {
            var site = Document.Sites[index % Document.Sites.Count];
            cases.Add(new CorpusCase(
                $"transition-{index:D5}-{site.Id}",
                CorpusCategory.TithiNakshatraTransitions,
                CelestialBody.Moon,
                epochs[index],
                site.Id,
                "tropical|mean-equinox-of-date|lahiri-sidereal-transition"));
        }
    }

    /// <summary>Sunrise/sunset at every declared site across the span, which includes polar day and night.</summary>
    private void EnumerateSunriseSunset(List<CorpusCase> cases)
    {
        var target = Document.CaseCounts.SunriseSunset;
        var epochs = Epochs(target, Document.Sites.Count);
        for (var index = 0; index < epochs.Count; index++)
        {
            var site = Document.Sites[index % Document.Sites.Count];
            cases.Add(new CorpusCase(
                $"sunrise-{index:D5}-{site.Id}",
                CorpusCategory.SunriseSunset,
                CelestialBody.Sun,
                epochs[index],
                site.Id,
                "apparent|upper-limb|refraction-standard"));
        }
    }

    /// <summary>Ascendant cases: the rising degree depends on site and sidereal time, not only on an instant.</summary>
    private void EnumerateLagna(List<CorpusCase> cases)
    {
        var target = Document.CaseCounts.Lagna;
        var epochs = Epochs(target, Document.Sites.Count * Document.Ayanamsas.Count);
        for (var index = 0; index < epochs.Count; index++)
        {
            var site = Document.Sites[index % Document.Sites.Count];
            var ayanamsa = Document.Ayanamsas[(index / Document.Sites.Count) % Document.Ayanamsas.Count];
            cases.Add(new CorpusCase(
                $"lagna-{index:D5}-{site.Id}-{ayanamsa}",
                CorpusCategory.Lagna,
                Body: null,
                epochs[index],
                site.Id,
                $"sidereal|{ayanamsa}"));
        }
    }

    /// <summary>Ayanamsa of date at every declared ayanamsa across the span, which is a claim about the offset itself.</summary>
    private void EnumerateAyanamsa(List<CorpusCase> cases)
    {
        var target = Document.CaseCounts.Ayanamsa;
        var epochs = Epochs(target, Document.Ayanamsas.Count);
        for (var index = 0; index < epochs.Count; index++)
        {
            var ayanamsa = Document.Ayanamsas[index % Document.Ayanamsas.Count];
            cases.Add(new CorpusCase(
                $"ayanamsa-{index:D5}-{ayanamsa}",
                CorpusCategory.Ayanamsa,
                Body: null,
                epochs[index],
                SiteId: null,
                $"sidereal-offset|{ayanamsa}"));
        }
    }

    /// <summary>
    /// Historical and edge-case dates: the spec's declared edge cases first, then the extremes of the fixture span
    /// (<see cref="ParityFixtures.From"/> to <see cref="ParityFixtures.To"/>), which is where ΔT is worst modelled.
    /// </summary>
    private void EnumerateHistoricalDates(List<CorpusCase> cases)
    {
        foreach (var edgeCase in Document.EdgeCases)
        {
            // Parsed as a LOCAL date at the edge case's own zone, then converted, because the point of a DST-gap or
            // DST-fold case is what the local calendar says on that day - parsing it as UTC would delete the edge it
            // exists to test.
            var zone = DateTimeZoneProviders.Tzdb.GetZoneOrNull(edgeCase.Timezone)
                       ?? throw new InvalidOperationException(
                           $"Edge case '{edgeCase.Id}' names unknown zone '{edgeCase.Timezone}'.");
            var localDate = LocalDatePattern.Iso.Parse(edgeCase.LocalDate).Value;

            // A date before the declared span is still carried, but it is not a span case: Paris local midnight in 1800
            // is 1799-12-31 UT, which sits 0.4 second before the span's own start. Refusing it would drop the Delta-T
            // edge the architect asked for; folding it into the span silently would be a wrong instant. The check in
            // HorizonsCorpusTests allows the edge cases a one-day margin and holds span cases to the span exactly.
            cases.Add(new CorpusCase(
                $"historical-{edgeCase.Id}",
                CorpusCategory.HistoricalDates,
                CelestialBody.Sun,
                // InZoneLeniently: on a DST spring-forward date the local midnight may not exist, and the lenient
                // mapping lands on the first valid instant rather than throwing - which is the behaviour the edge
                // case exists to exercise.
                JulianDay.FromInstant(localDate.At(LocalTime.Midnight).InZoneLeniently(zone).ToInstant()),
                edgeCase.Id,
                $"apparent|{edgeCase.Timezone}|dst-or-leap-second-edge"));
        }

        var target = Document.CaseCounts.HistoricalDates;
        var remaining = target - Document.EdgeCases.Count;
        var count = remaining;
        for (var index = 0; remaining > 0; index++, remaining--)
        {
            var epoch = FixtureSpanEpoch(index, count);
            cases.Add(new CorpusCase(
                $"historical-span-{index:D3}",
                CorpusCategory.HistoricalDates,
                CelestialBody.Sun,
                epoch,
                SiteId: null,
                "apparent|delta-t-extreme|span-endpoint"));
        }
    }

    /// <summary>
    /// Spreads <paramref name="count"/> epochs evenly across the declared UT span, phase-shifted per stride so bodies and
    /// sites do not all land on the same instants.
    /// </summary>
    /// <remarks>
    /// Even spreading is not sampling theory; it is reproducibility. Dense sampling at sign and nakshatra boundaries
    /// needs a body position to aim at, which this type deliberately does not compute - the corpus must not depend on
    /// the implementation under test to choose its own test instants.
    /// </remarks>
    private List<double> Epochs(int count, int stride)
    {
        var from = JulianDay.FromUtcMidnight(new LocalDate(Document.DateSpanUtYears.From, 1, 1));
        var to = JulianDay.FromUtcMidnight(new LocalDate(Document.DateSpanUtYears.To, 12, 31));
        var spread = (to - from) / count;
        var epochs = new List<double>(count);
        for (var index = 0; index < count; index++)
            epochs.Add(from + spread * (index + 0.5) + spread * (index % stride) / (stride * 4.0));
        return epochs;
    }

    /// <summary>
    /// An epoch at each end of the fixture span first, then evenly between them.
    /// </summary>
    /// <remarks>
    /// <paramref name="count"/> is the total number of span cases, not the number left: passing the countdown made the
    /// divisor shrink with the loop, so the first span case divided the whole span by one and landed in 1800. The
    /// original code also returned <c>from</c>/<c>to</c> for indices 0/1 and then ignored them, emitting an epoch out of
    /// range on the first iteration - a spread function that has to be tested is a spread function that was wrong.
    /// </remarks>
    private double FixtureSpanEpoch(int index, int count)
    {
        var from = JulianDay.FromUtcMidnight(new LocalDate(ParityFixtures.From.Year, ParityFixtures.From.Month,
            ParityFixtures.From.Day));
        var to = JulianDay.FromUtcMidnight(new LocalDate(ParityFixtures.To.Year, ParityFixtures.To.Month,
            ParityFixtures.To.Day));
        return count <= 1 ? from : from + (to - from) * (index / (double)(count - 1));
    }

    private static NodeConvention NodeConventionFor(CelestialBody body) => body switch
    {
        CelestialBody.TrueNode => NodeConvention.True,
        CelestialBody.MeanNode => NodeConvention.Mean,
        _ => NodeConvention.Mean
    };

    private static void Validate(CorpusSpecDocument document)
    {
        if (document.Bodies.Count == 0)
            throw new InvalidOperationException("AST-09 corpus spec declares no bodies.");
        if (document.Sites.Count < 20)
            throw new InvalidOperationException(
                $"AST-09 corpus spec declares {document.Sites.Count} sites; the architect's matrix requires at least 20 " +
                "spanning tropics, mid-latitudes and polar latitudes.");
        if (document.Ayanamsas.Count == 0)
            throw new InvalidOperationException("AST-09 corpus spec declares no ayanamsas.");
        if (document.MinimumTotalCases < 10_000)
            throw new InvalidOperationException(
                $"AST-09 requires at least 10000 cases; the spec declares {document.MinimumTotalCases}. Lowering this " +
                "number in data is exactly the narrowing acceptance criterion AC-1 forbids.");
        if (document.EdgeCases.Count > document.CaseCounts.HistoricalDates)
            throw new InvalidOperationException(
                $"AST-09 corpus spec declares {document.EdgeCases.Count} edge cases but only " +
                $"{document.CaseCounts.HistoricalDates} historical-date cases; the edge cases would not all be carried.");

        var declared = document.CaseCounts.Total;
        if (declared < document.MinimumTotalCases)
            throw new InvalidOperationException(
                $"AST-09 case counts sum to {declared}, below the required {document.MinimumTotalCases}.");
    }
}

/// <summary>The spec document as committed. Property names follow the camelCase JSON.</summary>
public sealed record CorpusSpecDocument(
    IReadOnlyList<CelestialBody> Bodies,
    DateSpan DateSpanUtYears,
    IReadOnlyList<CorpusSite> Sites,
    IReadOnlyList<AyanamsaKind> Ayanamsas,
    IReadOnlyList<CorpusEdgeCase> EdgeCases,
    CorpusCaseCounts CaseCounts,
    int MinimumTotalCases,
    CorpusTolerances Tolerances);

public sealed record DateSpan(int From, int To);

public sealed record CorpusSite(string Id, double LatitudeDegrees, double LongitudeDegrees, double ElevationMetres);

public sealed record CorpusEdgeCase(
    string Id,
    double LatitudeDegrees,
    double LongitudeDegrees,
    string Timezone,
    string LocalDate);

/// <summary>The per-category case budget. Its total must meet <see cref="CorpusSpecDocument.MinimumTotalCases"/>.</summary>
public sealed record CorpusCaseCounts(
    int PlanetaryPositions,
    int TithiNakshatraTransitions,
    int SunriseSunset,
    int Lagna,
    int Ayanamsa,
    int HistoricalDates)
{
    public int Total => PlanetaryPositions + TithiNakshatraTransitions + SunriseSunset + Lagna + Ayanamsa
                        + HistoricalDates;
}

/// <summary>The owner-approved accuracy targets, in the unit the comparison uses.</summary>
public sealed record CorpusTolerances(
    double PlanetsArcseconds,
    double MoonArcseconds,
    double LagnaArcseconds,
    double AyanamsaArcseconds,
    double EclipseContactSeconds,
    double SunriseSunsetSeconds)
{
    /// <summary>The arcsecond budget for a body, or a failure for a body with no approved target.</summary>
    /// <remarks>
    /// Throws rather than returning a permissive default: a body without a target has no accuracy claim, and a default
    /// would turn "unmeasured" into "passing" (issue #74 architect section C.3).
    /// </remarks>
    public double ArcsecondsFor(CelestialBody body) => body switch
    {
        CelestialBody.Sun => PlanetsArcseconds,
        CelestialBody.Moon => MoonArcseconds,
        CelestialBody.Mercury or CelestialBody.Venus or CelestialBody.Mars or CelestialBody.Jupiter
            or CelestialBody.Saturn or CelestialBody.Uranus or CelestialBody.Neptune or CelestialBody.Pluto
            or CelestialBody.MeanNode or CelestialBody.TrueNode => PlanetsArcseconds,
        _ => throw new InvalidOperationException(
            $"No owner-approved accuracy target exists for {body}, so no case may be scored against it.")
    };
}
