using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using MyVedicStar.Authorize.Data.Persistence.Entities;

namespace MyVedicStar.Authorize.Data.Persistence.Configurations;

internal sealed class UserLoginEntityConfiguration : IEntityTypeConfiguration<UserLoginEntity>
{
    public const string TableName = "UserLogin";

    public void Configure(EntityTypeBuilder<UserLoginEntity> builder)
    {
        builder.ToTable(TableName, AuthorizeDbContext.Schema);

        builder.HasKey(login => login.Id);
        builder.Property(login => login.Id).UseIdentityAlwaysColumn();

        // Generated by the database server so the audit time cannot be supplied by the caller.
        builder.Property(login => login.LoginTimeUtc)
            .HasColumnType("timestamp with time zone")
            .HasDefaultValueSql("now()")
            .ValueGeneratedOnAdd();

        builder.Property(login => login.IpAddress).HasColumnType("inet");

        builder.HasOne(login => login.User)
            .WithMany(user => user.Logins)
            .HasForeignKey(login => login.UserId)
            .OnDelete(DeleteBehavior.Cascade);

        builder.HasIndex(login => new { login.UserId, login.LoginTimeUtc });
    }
}
