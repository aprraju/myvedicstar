#!/bin/sh
set -eu
# Never enable shell tracing: the Entra token is a database password.
: "${AZURE_CLIENT_ID:?Required}"
: "${IDENTITY_ENDPOINT:?Required}"
: "${IDENTITY_HEADER:?Required}"
: "${Database__Host:?Required}"
: "${Database__Name:?Required}"
: "${Database__Username:?Required}"
: "${Database__AppRoleName:?Required}"
: "${Database__AppRoleObjectId:?Required}"
script_dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
PGPASSWORD=$(curl --fail --silent --show-error --get "$IDENTITY_ENDPOINT" \
  --data-urlencode 'resource=https://ossrdbms-aad.database.windows.net' \
  --data-urlencode 'api-version=2019-08-01' \
  --data-urlencode "client_id=$AZURE_CLIENT_ID" \
  -H "X-IDENTITY-HEADER: $IDENTITY_HEADER" | jq -er '.access_token | select(type == "string" and length > 0)')
export PGPASSWORD
export PGSSLROOTCERT=/etc/ssl/certs/ca-certificates.crt
export PGHOST="$Database__Host" PGDATABASE=postgres PGUSER="$Database__Username" PGSSLMODE=verify-full
psql -v app_role="$Database__AppRoleName" \
  -v app_object_id="$Database__AppRoleObjectId" \
  -v app_database="$Database__Name" -v migrator_role="$Database__Username" \
  -f "$script_dir/bootstrap-roles.sql"
# Apply the idempotent SQL generated by EF Core without tokens in argv.
export PGDATABASE="$Database__Name"
psql -v ON_ERROR_STOP=1 -f "$script_dir/migrations.sql"
unset PGPASSWORD
